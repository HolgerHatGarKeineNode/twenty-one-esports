import { SimplePool } from 'nostr-tools/pool';
import { finalizeEvent, generateSecretKey, getPublicKey } from 'nostr-tools/pure';
const url = 'ws://127.0.0.1:' + process.argv[2];
const sk = generateSecretKey();
const pk = getPublicKey(sk);
const pool = new SimplePool();
const got = [];
const sub = pool.subscribe([url], { kinds: [1059], '#p': [pk], since: 0 }, { onevent: (e) => got.push(e.id), oneose: () => got.push('EOSE') });
await new Promise((r) => setTimeout(r, 300));
const ev = finalizeEvent({ kind: 1059, created_at: Math.floor(Date.now() / 1000) - 100, tags: [['p', pk]], content: 'x' }, sk);
const res = await Promise.allSettled(pool.publish([url], ev));
await new Promise((r) => setTimeout(r, 300));
const other = finalizeEvent({ kind: 1059, created_at: 1, tags: [['p', 'ab'.repeat(32)]], content: 'y' }, sk);
await Promise.allSettled(pool.publish([url], other));
await new Promise((r) => setTimeout(r, 300));
console.log(JSON.stringify({ publish: res.map((r) => r.status + ':' + (r.value ?? r.reason)), got: got.map((g) => (g === ev.id ? 'mine' : g === other.id ? 'OTHER' : g)) }));
sub.close();
pool.destroy();
process.exit(0);
